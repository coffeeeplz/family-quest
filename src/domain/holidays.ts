/** 그날이 공휴일이면 이름을, 아니면 null 을 돌려준다. */
export function holidayName(day: string): string | null {
  const byDate = BY_DATE[day];
  if (byDate) return byDate;
  const year = Number(day.slice(0, 4));
  const fixed = FIXED.find((h) => h.md === day.slice(5) && year >= (h.from ?? 0));
  return fixed ? fixed.name : null;
}

/** 이 해의 설·추석 같은 날짜가 표에 들어 있는지 */
export const holidaysComplete = (year: number) => year >= 2026 && year <= HOLIDAY_TABLE_UNTIL;
